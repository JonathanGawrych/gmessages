-- v1 -> v2 (compatible with v2+): Durable incoming RPC streams
CREATE TABLE gmessages_incoming_rpc (
    bridge_id TEXT NOT NULL,
    login_id TEXT NOT NULL,
    response_id TEXT NOT NULL,
    digest BYTEA NOT NULL,
    payload BYTEA,
    PRIMARY KEY (bridge_id, login_id, response_id),
    FOREIGN KEY (bridge_id, login_id) REFERENCES user_login(bridge_id, id) ON DELETE CASCADE ON UPDATE CASCADE
);
CREATE TABLE gmessages_incoming_event (
    -- only: postgres
    sequence BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    -- only: sqlite (line commented)
--  sequence INTEGER PRIMARY KEY,
    bridge_id TEXT NOT NULL,
    login_id TEXT NOT NULL,
    response_id TEXT NOT NULL,
    stream TEXT NOT NULL,
    part_index INTEGER NOT NULL,
    FOREIGN KEY (bridge_id, login_id, response_id) REFERENCES gmessages_incoming_rpc(bridge_id, login_id, response_id) ON DELETE CASCADE ON UPDATE CASCADE,
    UNIQUE (bridge_id, login_id, response_id, part_index)
);
CREATE INDEX gmessages_incoming_event_stream ON gmessages_incoming_event(bridge_id, login_id, stream, sequence);
